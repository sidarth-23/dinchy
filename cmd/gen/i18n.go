package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"sort"
	"strings"
)

type i18nManifest struct {
	Messages []i18nMessage `json:"messages"`
}

type i18nMessage struct {
	Name         string            `json:"name"`
	Code         string            `json:"code"`
	Params       []i18nParam       `json:"params"`
	Translations map[string]string `json:"translations"`
}

type i18nParam struct {
	Name string `json:"name"`
	Type string `json:"type"`
}

func runI18n(args []string) error {
	fs := flag.NewFlagSet("i18n", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	input := fs.String("input", "messages.json", "manifest input path")
	output := fs.String("output", "generated.go", "generated Go output path")
	if err := fs.Parse(args); err != nil {
		return err
	}
	return generateI18n(*input, *output)
}

func generateI18n(inputPath, outputPath string) error {
	raw, err := os.ReadFile(inputPath)
	if err != nil {
		return err
	}

	var mf i18nManifest
	if err := json.Unmarshal(raw, &mf); err != nil {
		return err
	}
	if err := validateI18nManifest(mf); err != nil {
		return err
	}

	src, err := renderI18nManifest(mf)
	if err != nil {
		return err
	}
	return writeGeneratedFile(outputPath, src)
}

func validateI18nManifest(mf i18nManifest) error {
	seenNames := map[string]struct{}{}
	seenCodes := map[string]struct{}{}
	langs := map[string]struct{}{}

	for _, msg := range mf.Messages {
		if msg.Name == "" {
			return fmt.Errorf("message name cannot be empty")
		}
		if msg.Code == "" {
			return fmt.Errorf("message %q has empty code", msg.Name)
		}
		if _, ok := seenNames[msg.Name]; ok {
			return fmt.Errorf("duplicate message name %q", msg.Name)
		}
		if _, ok := seenCodes[msg.Code]; ok {
			return fmt.Errorf("duplicate message code %q", msg.Code)
		}
		seenNames[msg.Name] = struct{}{}
		seenCodes[msg.Code] = struct{}{}

		paramNames := map[string]struct{}{}
		for _, p := range msg.Params {
			if p.Name == "" {
				return fmt.Errorf("message %q has a param with empty name", msg.Name)
			}
			if p.Type == "" {
				return fmt.Errorf("message %q param %q has empty type", msg.Name, p.Name)
			}
			if _, ok := paramNames[p.Name]; ok {
				return fmt.Errorf("message %q has duplicate param %q", msg.Name, p.Name)
			}
			paramNames[p.Name] = struct{}{}
		}

		if len(msg.Translations) == 0 {
			return fmt.Errorf("message %q has no translations", msg.Name)
		}
		for lang, text := range msg.Translations {
			if text == "" {
				return fmt.Errorf("message %q has empty translation for %q", msg.Name, lang)
			}
			langs[lang] = struct{}{}
		}
	}

	if _, ok := langs["en"]; !ok {
		return fmt.Errorf("manifest must include an en translation")
	}
	return nil
}

func renderI18nManifest(mf i18nManifest) ([]byte, error) {
	sort.Slice(mf.Messages, func(i, j int) bool { return mf.Messages[i].Code < mf.Messages[j].Code })

	var b strings.Builder
	b.WriteString("// Code generated by cmd/gen i18n; DO NOT EDIT.\n\n")
	b.WriteString("package i18n\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"golang.org/x/text/language\"\n")
	b.WriteString(")\n\n")
	b.WriteString("type Code string\n\n")
	b.WriteString("const (\n")
	for _, msg := range mf.Messages {
		fmt.Fprintf(&b, "\tCode%s Code = %q\n", msg.Name, msg.Code)
	}
	b.WriteString(")\n\n")
	b.WriteString("var CatalogData = map[language.Tag]map[Code]string{\n")
	b.WriteString("\tlanguage.English: {\n")
	for _, msg := range mf.Messages {
		translation := msg.Translations["en"]
		fmt.Fprintf(&b, "\t\tCode%s: %q,\n", msg.Name, translation)
	}
	b.WriteString("\t},\n")
	b.WriteString("}\n\n")

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, err
	}
	return formatted, nil
}
