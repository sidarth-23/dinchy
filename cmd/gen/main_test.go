func TestGenerateEventUsesSourceManifest(t *testing.T) {
	t.Parallel()

	tmpDir := t.TempDir()
	out := filepath.Join(tmpDir, "generated.go")
	input := filepath.Join("..", "..", "internal", "events", "catalog.json")

	raw, err := os.ReadFile(input)
	require.NoError(t, err)

	var mf eventManifest
	require.NoError(t, json.Unmarshal(raw, &mf))
	require.NoError(t, generateEvent(input, out))

	got, err := os.ReadFile(out)
	require.NoError(t, err)

	require.Contains(t, string(got), "// Code generated by cmd/gen event; DO NOT EDIT.")
	require.Contains(t, string(got), "package events")
	require.Contains(t, string(got), "type Definition struct")
	require.Contains(t, string(got), "type AuthSecurityAuthLoginSucceededMetadata struct")
	require.Contains(t, string(got), "func (value AuthSecurityAuthLoginSucceededMetadata) Map() map[string]any")
	require.Contains(t, string(got), "type AuthSecuritySSOSettingsUpdatedChanges struct")

	normalizedGot := normalize(string(got))
	require.Contains(t, normalizedGot, "ClientIDbool")
	require.Contains(t, normalizedGot, "CallbackURLbool")
	events := flattenTestEvents(mf.Modules, nil)
	for _, event := range events {
		require.Contains(t, normalizedGot, normalize(event.ConstantName+" Type = "+quote(event.Type)))
		require.Contains(t, normalizedGot, normalize("ID: "+quote(event.ID)))
		require.Contains(t, normalizedGot, normalize("Module: "+quote(event.Module)))
		require.Contains(t, normalizedGot, normalize("Category: "+quote(event.Category)))
		require.Contains(t, normalizedGot, normalize("Subcategory: "+quote(event.Subcategory)))
		require.Contains(t, normalizedGot, normalize("Action: "+quote(event.Action)))
		require.Contains(t, normalizedGot, normalize("Outcome: "+quote(event.Outcome)))
		if event.Description != "" {
			require.Contains(t, normalizedGot, normalize("Description: "+quote(event.Description)))
		}
	}

	require.Contains(t, normalizedGot, normalize("\"email\": value.Email"))
	require.Contains(t, normalizedGot, normalize("\"enabled\": value.Enabled"))
	require.Contains(t, normalizedGot, normalize("\"client_id\": value.ClientID"))
	require.Contains(t, normalizedGot, normalize("\"callback_url\": value.CallbackURL"))
}

