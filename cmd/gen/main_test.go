func quote(s string) string {
	return strconv.Quote(s)
}

func normalize(s string) string {
	return strings.Map(func(r rune) rune {
		if unicode.IsSpace(r) {
			return -1
		}
		return r
	}, s)
}

func flattenTestEvents(modules []eventModule, modulePath []string) []flattenedTestEvent {
	out := make([]flattenedTestEvent, 0)
	for _, module := range modules {
		currentModulePath := append(append([]string{}, modulePath...), module.ID)
		for _, category := range module.Categories {
			currentCategoryPath := append(append([]string{}, currentModulePath...), category.ID)
			for _, subcategory := range category.Subcategories {
				currentSubcategoryPath := append(append([]string{}, currentCategoryPath...), subcategory.ID)
				for _, event := range subcategory.Events {
					out = append(out, flattenedTestEvent{
						ID:           event.ID,
						Type:         eventTypeFor(currentSubcategoryPath, event.ID),
						Module:       displayPath(currentModulePath),
						Category:     category.ID,
						Subcategory:  subcategory.ID,
						Action:       event.Action,
						Outcome:      event.Outcome,
						Description:  event.Description,
						ConstantName: eventConstantName(currentSubcategoryPath, event.ID),
					})
				}
			}
		}
	}
	return out
}

type flattenedTestEvent struct {
	ID           string
	Type         string
	Module       string
	Category     string
	Subcategory  string
	Action       string
	Outcome      string
	Description  string
	ConstantName string
}
