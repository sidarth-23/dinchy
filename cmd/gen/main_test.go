func TestGenerateErrorUsesSourceManifest(t *testing.T) {
	t.Parallel()

	tmpDir := t.TempDir()
	out := filepath.Join(tmpDir, "generated.go")
	input := filepath.Join("..", "..", "internal", "errors", "meta.json")

	raw, err := os.ReadFile(input)
	require.NoError(t, err)

	var mf errorManifest
	require.NoError(t, json.Unmarshal(raw, &mf))
	require.NoError(t, generateError(input, out))

	got, err := os.ReadFile(out)
	require.NoError(t, err)

	require.Contains(t, string(got), "// Code generated by cmd/gen error; DO NOT EDIT.")
	require.Contains(t, string(got), "package errors")
	require.Contains(t, string(got), "type MetaKey string")

	normalizedGot := normalize(string(got))
	for _, group := range mf.Groups {
		metaKeyName := group.KeyName
		if metaKeyName == "" {
			metaKeyName = group.Name
		}
		optionName := group.OptionName
		if optionName == "" {
			optionName = "With" + group.Name
		}
		require.Contains(t, normalizedGot, normalize("MetaKey"+metaKeyName+" MetaKey = "+quote(group.MetaKey)))
		require.Contains(t, normalizedGot, normalize("type "+group.Name+" "))
		require.Contains(t, normalizedGot, normalize("func "+optionName+"("))
		for _, v := range group.Values {
			require.Contains(t, normalizedGot, normalize(group.Name+v.Name+" "+group.Name+" = "+quote(v.Value)))
		}
	}
}

